// src/spec/trace.ts -- `nen spec trace`: `<root>/traceability.md` regenerated
// for one product family from every folder's spec.md, tasks.md and parity.md,
// never edited by hand (zheref/nen#493 AC-10).
//
// ONE ROW PER REQUIREMENT, ONE COLUMN PER MEMBER. Each FR and SC is named by its
// qualified id (`F<nnn>-FR-###`); a member's cell is its parity.md state when
// the folder records one, else the number of that member's citations on the
// line, else `—`; then the tasks naming the requirement and the line's open
// markers. Nothing is inferred: every cell is a count or a word read from a
// file.
//
// THE FILE CAN TELL A HAND EDIT FROM A STALE ONE, exactly as `spec index`'s
// can: its first line is a marker holding the sha256 of every byte below it,
// and `--write` refuses to overwrite a body that no longer hashes to it.

import { lstatSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative } from "node:path";
import { sha256 } from "./check.js";
import { citationsIn, markersIn, proseLines, requirementOf } from "./lines.js";
import type { SpecLayout } from "./layout.js";
import { parseParity, readCell, readParityFolders } from "./parity.js";
import { parseTasks } from "./tasks.js";
import { generatedState, type IndexState } from "./specindex.js";

export const SPEC_TRACE_CONTRACT = "nen.spec.trace/v0.1";
export const TRACE_MARKER_PREFIX = "<!-- generated by nen spec trace; regenerate with 'nen spec trace --write', never edit by hand · sha256:";

export interface TraceRow {
  readonly folder: string;
  readonly id: string;
  readonly cells: Readonly<Record<string, string>>;
  readonly tasks: readonly string[];
  readonly markers: number;
}

/** KEY ORDER IS THE DOCUMENTED `--json` SHAPE. */
export interface TraceReport {
  readonly contract: string;
  readonly verdict: IndexState | "could-not-read";
  readonly repo: string;
  readonly family: string;
  readonly members: readonly string[];
  readonly path: string;
  readonly rows: readonly TraceRow[];
  readonly action: "none" | "written" | "would-write" | "refused";
  readonly reason: string | null;
}

const cell = (value: string): string => value.replace(/\|/g, "\\|");

export function traceRows(repo: string, layout: SpecLayout, members: readonly string[]): TraceRow[] {
  const rows: TraceRow[] = [];
  for (const folder of readParityFolders(repo, layout, null)) {
    const parsed = folder.parity === null ? null : parseParity(folder.parity);
    let tasks: ReturnType<typeof parseTasks> = [];
    const tasksPath = join(repo, folder.folder, "tasks.md");
    if (lstatSync(tasksPath, { throwIfNoEntry: false })?.isFile() === true) tasks = parseTasks(readFileSync(tasksPath, "utf8"));
    for (const line of proseLines(folder.spec)) {
      const requirement = requirementOf(line.text);
      if (requirement === null || requirement.kind === "US") continue;
      const cells: Record<string, string> = {};
      for (const code of members) {
        const recorded = parsed?.cells.get(requirement.id)?.get(code);
        const cites = citationsIn(line.text).filter((entry): boolean => entry.citation?.code === code).length;
        cells[code] = recorded !== undefined ? (readCell(recorded, code).state ?? "malformed") : cites > 0 ? `${cites} citation(s)` : "—";
      }
      rows.push({
        folder: folder.folder,
        id: `F${folder.nnn}-${requirement.kind}-${requirement.id.slice(3).padStart(3, "0")}`,
        cells,
        tasks: tasks.filter((task): boolean => task.requirements.includes(requirement.id)).map((task): string => task.id),
        markers: markersIn(line.text).length,
      });
    }
  }
  return rows;
}

export function renderTraceBody(family: string, members: readonly string[], rows: readonly TraceRow[]): string {
  return [
    `# Traceability — ${family}`,
    "",
    `| Requirement | ${members.map(cell).join(" | ")} | Tasks | Open markers |`,
    `|---|${members.map((): string => "---|").join("")}---|---|`,
    ...rows.map((row): string => `| ${row.id} | ${members.map((code): string => cell(row.cells[code] ?? "—")).join(" | ")} | ${row.tasks.join(", ") || "—"} | ${row.markers} |`),
    "",
  ].join("\n");
}

export function specTrace(repo: string, layout: SpecLayout, family: string, members: readonly string[], options: { readonly write: boolean; readonly dryRun: boolean }): TraceReport {
  const relativePath = `${layout.root}/traceability.md`;
  const make = (verdict: TraceReport["verdict"], rows: readonly TraceRow[], action: TraceReport["action"], reason: string | null): TraceReport => ({ contract: SPEC_TRACE_CONTRACT, verdict, repo, family, members, path: relativePath, rows, action, reason });
  let rows: TraceRow[];
  try {
    rows = traceRows(repo, layout, members);
  } catch (error) {
    return make("could-not-read", [], options.write ? "refused" : "none", (error as Error).message);
  }
  const path = join(repo, relativePath);
  const stat = lstatSync(path, { throwIfNoEntry: false });
  if (stat !== undefined && !stat.isFile()) return make("could-not-read", rows, options.write ? "refused" : "none", `${relativePath} is not a regular file (a link or a directory); nen reads and writes no trace through one`);
  const existing = stat === undefined ? null : readFileSync(path, "utf8");
  const body = renderTraceBody(family, members, rows);
  const generated = `${TRACE_MARKER_PREFIX}${sha256(body)} -->\n${body}`;
  const state = generatedState(existing, generated, TRACE_MARKER_PREFIX);
  if (!options.write || state === "current") return make(state, rows, "none", null);
  if (state === "hand-edited") return make(state, rows, "refused", `${relativePath} was edited by hand (its body does not hash to its marker, or it has none); nen will not overwrite an edit it cannot judge`);
  const inside = relative(realpathSync(repo), realpathSync(join(repo, layout.root)));
  if (inside === "" || inside.startsWith("..") || isAbsolute(inside)) return make(state, rows, "refused", `${layout.root}/ resolves outside --repo; nen writes no trace through a link`);
  if (options.dryRun) return make(state, rows, "would-write", null);
  writeFileSync(path, generated);
  return make(state, rows, "written", null);
}

export function renderTrace(report: TraceReport): string[] {
  if (report.verdict === "could-not-read") return [`could-not-read: ${report.path} -- ${report.reason ?? ""}`];
  return [
    `${report.path}: ${report.verdict} · action ${report.action} · family ${report.family} (${report.members.join(", ")}) · ${report.rows.length} requirement(s)${report.reason === null ? "" : ` -- ${report.reason}`}`,
  ];
}
