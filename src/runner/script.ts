function posixPreamble(plan: RunnerPlan, version: string, what: string, runAs: string): string[] {
  const [owner, repo] = plan.target.split("/") as [string, string];
  return [
    "#!/usr/bin/env bash",
    ...header(plan, version, "#", "—", what),
    "#",
    ...runAs.split("\n").map((line): string => `# ${line}`.trimEnd()),
    "#",
    "# Exit codes: 0 every planned runner's service is running; 1 anything else;",
    "# 3 run as the wrong user; 5 gh missing or not signed in; 6 the runner",
    "# package failed its SHA-256 check (the file is deleted). The one summary",
    "# line is also written to $PROJECT_DIR/_jusshin/register-<ts>.summary.",
    "set -euo pipefail",
    "",
    `TARGET=${sh(plan.target)}`,
    `REPO_URL=${sh(`https://github.com/${plan.target}`)}`,
    `LABELS=${sh(plan.labels.join(","))}`,
    `ROOT=${sh(plan.root)}`,
    `PROJECT_DIR=${sh(plan.projectDir)}`,
    `DOWNLOAD_URL=${sh(plan.download.download_url)}`,
    `ARCHIVE=${sh(plan.download.filename)}`,
    `SHA256=${sh(plan.download.sha256_checksum.toLowerCase())}`,
    `SERVICE_PREFIX=${sh(`actions.runner.${owner}-${repo}.`)}`,
    "RUNNERS=(",
    ...plan.runners.map((runner): string => `  ${sh(`${runner.name}|${runner.installDir}`)}`),
    ")",
    'WORK_DIR="$PROJECT_DIR/_jusshin"',
    "registered=0",
    "skipped=0",
    "failed=0",
    'stamp="$(date +%Y%m%d-%H%M%S)"',
    'summary_file=""',
    "",
    "# The summary file carries the ONE summary line and nothing else: it is what",
    "# the caller reads. The log is the maintainer's.",
    "finish() {",
    '  summary="jusshin: ${registered} registered, ${skipped} skipped, ${failed} failed"',
    '  echo "$summary"',
    `  if [ -n "$summary_file" ]; then printf '%s\\n' "$summary" > "$summary_file" || true; fi`,
    '  exit "$1"',
    "}",
    "",
    "# Whether a runner directory is already configured as NAME (idempotent re-run).",
    "configured_as() {",
    '  [ -f "$1/.runner" ] && grep -q "\\"agentName\\": *\\"$2\\"" "$1/.runner"',
    "}",
    "",
    "# Why a directory configured as NAME is stale, or nothing when it stands: its",
    "# service is absent ($2 is not 1), or GitHub no longer lists its registration",
    "# ($3, one name per line) (#319).",
    "stale_reason() {",
    '  local reasons=""',
    '  if [ "$2" != 1 ]; then reasons="its service is absent"; fi',
    "  # A here-string, never a pipe: under pipefail, grep -q exiting on an early",
    "  # match would SIGPIPE a long printf and read a listed name as unlisted.",
    "  if ! grep -Fxq -- \"$1\" <<<\"$3\"; then",
    '    reasons="${reasons:+$reasons and }GitHub no longer lists its registration"',
    "  fi",
    "  printf '%s' \"$reasons\"",
    "}",
    "",
    "# The names GitHub lists for the repository's runners, read once into",
    "# $listed; $listed_ok is 1 when the read succeeded.",
    'listed=""',
    'listed_ok=""',
    "read_listed() {",
    '  if [ -n "$listed_ok" ]; then return 0; fi',
    "  if listed=\"$(gh_run api --paginate \"repos/$TARGET/actions/runners\" --jq '.runners[].name' 2>/dev/null)\"; then listed_ok=1; else listed_ok=0; fi",
    "}",
    "",
    "# Stop and uninstall a stale runner's service from its own directory.",
    "remove_service() {",
    "  # A stop that fails is a failure: deleting a directory under a live listener",
    "  # is the one thing this must not do.",
    '  (cd "$1" && ./svc.sh stop && ./svc.sh uninstall)',
    "}",
    "",
  ];
}

function posixDownload(checker: string): string[] {
  return [
    'archive="$WORK_DIR/$ARCHIVE"',
    "verify_archive() {",
    `  echo "$SHA256  $archive" | ${checker} >/dev/null 2>&1`,
    "}",
    "if [ \"${#pending[@]}\" -gt 0 ]; then",
    '  if [ ! -f "$archive" ] || ! verify_archive; then',
    '    echo "jusshin: downloading $ARCHIVE"',
    '    curl -fsSL -o "$archive" "$DOWNLOAD_URL"',
    "    if ! verify_archive; then",
    '      rm -f "$archive"',
    '      echo "jusshin: $ARCHIVE failed its SHA-256 check (expected $SHA256) -- deleted."',
    "      finish 6",
    "    fi",
    "  fi",
    '  echo "jusshin: $ARCHIVE verified (sha256 $SHA256)."',
    "fi",
    "",
  ];
}

const POSIX_PENDING = [
  "pending=()",
  'replace_names=" "',
  'for entry in "${RUNNERS[@]}"; do',
  '  name="${entry%%|*}"',
  '  dir="${entry#*|}"',
  '  if configured_as "$dir" "$name"; then',
  "    # Configured is not standing (#319): a failed service install leaves .runner",
  "    # behind with no service, and a removed registration leaves one GitHub no",
  "    # longer lists. Either is stale -- emptied and re-registered, never skipped.",
  "    read_listed",
  '    if [ "$listed_ok" != 1 ]; then',
  "      echo \"jusshin: could not list the runners of $TARGET, so $name in $dir cannot be told live from stale -- left untouched (the gh user must be an admin of $TARGET).\"",
  "      failed=$((failed + 1))",
  "      continue",
  "    fi",
  '    if ! has_service="$(service_present "$name")"; then',
  '      echo "jusshin: the service state of $name could not be read, so $dir cannot be told live from stale -- left untouched."',
  "      failed=$((failed + 1))",
  "      continue",
  "    fi",
  '    reason="$(stale_reason "$name" "$has_service" "$listed")"',
  '    if [ -z "$reason" ]; then',
  '      echo "jusshin: $name is already configured in $dir -- skipped."',
  "      skipped=$((skipped + 1))",
  "      continue",
  "    fi",
  '    echo "jusshin: $name in $dir is stale ($reason) -- emptied and re-registered."',
  '    if [ "$has_service" = 1 ] && ! remove_service "$dir"; then',
  '      echo "jusshin: svc.sh could not stop or uninstall the stale service for $name; $dir left untouched."',
  "      failed=$((failed + 1))",
  "      continue",
  "    fi",
  "    # Under set -e a bare rm that fails would end the run with no summary: a",
  "    # directory that cannot be emptied fails this runner alone.",
  '    if ! rm -rf "$dir"; then',
  '      echo "jusshin: could not empty $dir for $name."',
  "      failed=$((failed + 1))",
  "      continue",
  "    fi",
  "    # A stale runner GitHub still lists is replaced under its own name.",
  "    if grep -Fxq -- \"$name\" <<<\"$listed\"; then replace_names=\"$replace_names$name \"; fi",
  '    pending+=("$entry")',
  "    continue",
  "  fi",
  '  if [ -f "$dir/.runner" ]; then',
  '    echo "jusshin: $dir holds a runner configured as another name, not $name -- left untouched."',
  "    failed=$((failed + 1))",
  "    continue",
  "  fi",
  '  pending+=("$entry")',
  "done",
  "",
];

