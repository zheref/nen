// src/runner/script.ts -- `nen runner script`: the HOST script that registers a
// plan's runners as boot-persistent services, rendered deterministically, one
// per operating system.
//
// NEN RENDERS; NEN NEVER RUNS IT. The script registers Windows services, grants
// folder rights and asks for a service account's password -- every one of
// those is an act on the maintainer's machine that the maintainer consents to
// (a UAC prompt on Windows, their own `sudo` on Linux). So the verb's whole
// output is a file and the ONE command line that launches it; running that
// line is the caller's, and on Windows the elevation is the human's.
//
// THE SECRETS NEVER PASS THROUGH NEN. The registration token is minted INSIDE
// the script, by `gh`, at the moment `config` needs it, into a variable that
// is never printed; the Windows account password is typed ONCE into
// `Read-Host -AsSecureString`, checked against the refused-character rule
// before its first use, and turned into plain text only for the one config
// call. NEITHER SECRET IS EVER ON A COMMAND LINE (#312, SEC-1): `config.cmd` is
// a batch file cmd.exe re-parses, so `& | < > ^ %` in an argument split it,
// expanded it or ran a command. Both reach the runner through its
// `ACTIONS_RUNNER_INPUT_<ARG>` environment inputs instead (actions/runner's
// CommandSettings.cs reads, masks and removes them), set on this process only
// for the child's lifetime and cleared in a `finally`. Config's own output is
// DISCARDED, never replayed into the transcript: its exit code and a fixed
// line are all the log carries. The bash scripts pass the token the same way.
//
// THE RUNNER ROOT IS LOCKED BEFORE IT IS USED (#312, SEC-9). A root an
// unelevated session created inherits `Authenticated Users: Modify` from the
// drive; the Windows script takes ownership for Administrators, removes the
// inherited entries and grants SYSTEM and Administrators full control BEFORE
// anything is downloaded or run from it, keeps the package in an admin-only
// `_jusshin\pkg`, and re-hashes it before every extraction. The script ITSELF
// is protected by where it is written: `nen runner script` refuses an `--out`
// under the plan's root, and the docs place it in the user's profile.
//
// DETERMINISTIC TO THE BYTE. No timestamp, no host name, no random value is
// rendered: the transcript's own file name is computed by the SCRIPT when it
// runs. The version in the header is a parameter so the golden files
// (./fixtures/*.golden) survive a release.
//
// POWERSHELL 5.1, NOT 7. The Windows host this was built for has no `pwsh`, and
// a runner host is exactly the machine nobody has provisioned yet: no `&&`, no
// `??`, no ternary, ASCII only (5.1 reads a BOM-less file as the ANSI code page,
// so an em dash in the header would render as mojibake -- the bash scripts
// carry it, the .ps1 writes `--`). Native commands run with
// `$ErrorActionPreference = 'Continue'` around them, because under 'Stop' a
// 5.1 host turns any stderr line of a native program into a terminating error.

//
// AN INTERACTIVE WINDOWS POOL IS A LOGON TASK, NEVER A SERVICE (#333). A
// service runs in session 0, which has no desktop, so a job that drives a real
// UI times out there. For `mode: interactive` the script configures the runner
// WITHOUT `--runasservice`, grants the identity Modify on its own runner folder,
// and registers a Scheduled Task that starts `run.cmd` at that identity's logon,
// in its desktop session (interactive token: no password is asked or stored),
// restarting on failure, with no time limit. Every other guarantee above holds:
// the locked root, the re-hashed package, the token through the environment,
// the summary file.

import type { RunnerPlan } from "./plan.js";
import { isLogonTask, NETWORK_SERVICE } from "./plan.js";

export interface RenderedScript {
  readonly os: RunnerPlan["os"];
  readonly text: string;
  readonly needsElevation: boolean;
}

/**
 * The characters a Windows service-account password may not carry (#312,
 * SEC-1): the ones cmd.exe or PowerShell read as syntax, plus a line break.
 * The script refuses such a password before its first use, as defense in depth
 * behind the environment path -- and names this rule when it does.
 */
export const REFUSED_PASSWORD_CHARACTERS = `& | < > ^ % " ' or a line break`;

/** The same set as a regular expression; .NET and JavaScript read this class identically. */
export const REFUSED_PASSWORD_PATTERN = `[&|<>^%"'\\r\\n]`;

/** The summary file(s) a run leaves, as a glob under the project dir's _jusshin folder. */
export function summaryGlob(plan: RunnerPlan): string {
  const sep = plan.os === "Windows" ? "\\" : "/";
  return `${plan.projectDir}${sep}_jusshin${sep}register-*.summary`;
}

/** A PowerShell single-quoted literal. Plan values are validated to carry no quote; this is the second belt. */
function ps(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

/** A bash single-quoted literal, same reasoning. */
function sh(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function header(plan: RunnerPlan, version: string, comment: string, dash: string, what: string): string[] {
  return [
    `${comment} jusshin ${dash} register self-hosted GitHub Actions runners ${what}.`,
    `${comment} rendered by nen ${version} runner script ${dash} do not edit; re-run nen runner script`,
    `${comment}`,
    `${comment} target:   ${plan.target}`,
    `${comment} pool:     ${plan.pool} (${plan.labels.join(",")})`,
    `${comment} runners:  ${plan.runners.map((runner): string => runner.name).join(", ")}`,
    `${comment} identity: ${plan.identity}`,
    `${comment} root:     ${plan.root}`,
    `${comment} package:  ${plan.download.filename} (runner ${plan.runnerVersion})`,
  ];
}

