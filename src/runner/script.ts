    "            $script:ListOk = $true",
    "        }",
    "    } finally {",
    "        $ErrorActionPreference = $previous",
    "    }",
    "}",
    "",
    "function Start-Log {",
    "    Start-Transcript -Path $script:LogPath -Append | Out-Null",
    "    $script:Transcribing = $true",
    "}",
    "",
