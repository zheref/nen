// src/dev/ordinary-words.ts -- regenerates src/issue/ordinary-words.json, the
// private-name guard's ordinary-word list (zheref/nen#535), from the SCOWL
// 2020.12.07 release tarball, and checks the committed copy against it.
//
// A REPOSITORY SCRIPT, NOT A VERB, in src/dev/ beside matrix.ts for the same
// reason: this repository's own dev loop, in TypeScript rather than shell.
//
// WHY IT EXISTS (Feitan F5 on NN-PR-#541). One word added to a 10,737-line
// JSON diff silently lifts the bare-word match for that word, and no reviewer
// sees it. So the list is DERIVED, never edited: this script verifies the
// tarball's sha256, extracts the four lists and SCOWL's Copyright file,
// derives the words (`deriveOrdinaryWords`) and renders the document
// (`renderOrdinaryWordsDoc`). ordinary-words.test.ts renders the committed
// words in memory and compares the result to the committed file byte for byte,
// and it pins the count and the words' sha256. A changed list therefore shows
// up as a changed pin in a reviewable diff, or as a red build.
//
// USAGE
//   bun src/dev/ordinary-words.ts --tarball <scowl-2020.12.07.tar.gz> [--write]
//     without --write: exit 0 when the committed JSON and Copyright file are
//     the derivation's, exit 1 naming what drifted; --write rewrites both.
//   The tarball: SCOWL_URL below (SourceForge), sha256 SCOWL_SHA256.

import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

export const SCOWL_URL = "https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz";

/** The tarball's sha256, computed when the list was vendored (2026-10-25). */
export const SCOWL_SHA256 = "5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc";

const ROOT = "scowl-2020.12.07";

/** The lists read, by their path inside the tarball. */
export const SCOWL_FILES = {
  words10: `${ROOT}/final/english-words.10`,
  words20: `${ROOT}/final/english-words.20`,
  upper10: `${ROOT}/final/english-upper.10`,
  upper35: `${ROOT}/final/english-upper.35`,
} as const;

export const COPYRIGHT_IN_TARBALL = `${ROOT}/Copyright`;

/** Where the derivation lands, repo-relative. */
export const JSON_PATH = "src/issue/ordinary-words.json";
export const COPYRIGHT_PATH = "src/issue/ordinary-words.COPYRIGHT";

/** The only names english-upper.35 contributes: the twelve months and seven weekdays. */
const CALENDAR = new Set([
  "January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December",
  "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday",
]);

/** One SCOWL file's text (Latin-1), split into lines. */
function entries(text: string): readonly string[] {
  return text.split(/\r?\n/).filter((line): boolean => line !== "");
}

/**
 * The derivation: english-words.10, english-words.20, english-upper.10 and the
 * calendar names of english-upper.35; only entries made of ASCII letters (so
 * every possessive and every accented word is dropped), lowercased,
 * de-duplicated, sorted bytewise.
 */
export function deriveOrdinaryWords(files: { readonly [K in keyof typeof SCOWL_FILES]: string }): readonly string[] {
  const picked = [
    ...entries(files.words10),
    ...entries(files.words20),
    ...entries(files.upper10),
    ...entries(files.upper35).filter((entry): boolean => CALENDAR.has(entry)),
  ];
  const words = new Set(picked.filter((entry): boolean => /^[A-Za-z]+$/.test(entry)).map((entry): string => entry.toLowerCase()));
  return [...words].sort((a, b): number => (a < b ? -1 : a > b ? 1 : 0));
}

/** The sha256 of the words, one per line, each line ending in a newline. */
export function wordsSha256(words: readonly string[]): string {
  return createHash("sha256").update(words.map((word): string => `${word}\n`).join("")).digest("hex");
}

/** The committed document, rendered from the words. Deterministic: no date, no version. */
export function renderOrdinaryWordsDoc(words: readonly string[]): string {
  const doc = {
    $comment:
      "The ordinary-word list the private-name guard reads (zheref/nen#535; src/issue/ordinary-words.ts loads it, docs/USAGE.md 'Ordinary-word names' states the rule). A private repository whose WHOLE name equals one of these words, case-insensitive and with nothing stripped, is matched only in repository-shaped forms (owner/name, name#N, name.git, a URL path), never as a bare word. Data, embedded in the binary by the bundler, so the decision is the same on every host and never reads a host dictionary. GENERATED by src/dev/ordinary-words.ts from the SCOWL 2020.12.07 tarball (sha256 in `tarballSha256`): english-words.10, english-words.20 and english-upper.10, plus the twelve month and seven weekday names of english-upper.35; entries with an apostrophe or any character outside A-Z/a-z dropped, lowercased, deduplicated, sorted bytewise. Never edit by hand -- src/dev/ordinary-words.test.ts pins `count` and `wordsSha256`, and a word to clear one refusal belongs in the caller's ignore file. SCOWL's Copyright file is vendored verbatim beside this one (`copyrightFile`).",
    source: `SCOWL 2020.12.07 -- ${SCOWL_URL} (final/english-words.10, final/english-words.20, final/english-upper.10, and the month and weekday names of final/english-upper.35)`,
    tarballSha256: SCOWL_SHA256,
    copyrightFile: COPYRIGHT_PATH,
    licence:
      "The collective work is Copyright 2000-2018 by Kevin Atkinson as well as any of the copyrights mentioned below: Copyright 2000-2018 by Kevin Atkinson. Permission to use, copy, modify, distribute and sell these word lists, the associated scripts, the output created from the scripts, and its documentation for any purpose is hereby granted without fee, provided that the above copyright notice appears in all copies and that both that copyright notice and this permission notice appear in supporting documentation. Kevin Atkinson makes no representations about the suitability of this array for any purpose. It is provided \"as is\" without express or implied warranty. The notices of every source SCOWL draws on (Moby Words II and Brian Kelk's UK English Wordlist, both public domain; VarCon; WordNet; and the others SCOWL names) are retained verbatim in the copyrightFile.",
    count: words.length,
    wordsSha256: wordsSha256(words),
    words,
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function sha256File(path: string): string {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

/** The entry point. Returns the exit code. */
export function ordinaryWordsMain(argv: readonly string[], repo: string = process.cwd()): number {
  const at = argv.indexOf("--tarball");
  const tarball = at === -1 ? undefined : argv[at + 1];
  const write = argv.includes("--write");
  if (tarball === undefined || argv.some((arg, i): boolean => arg.startsWith("--") && arg !== "--tarball" && arg !== "--write" && i !== at + 1)) {
    console.error(`usage: bun src/dev/ordinary-words.ts --tarball <scowl-2020.12.07.tar.gz> [--write]   (${SCOWL_URL})`);
    return 2;
  }
  const actual = sha256File(tarball);
  if (actual !== SCOWL_SHA256) {
    console.error(`ordinary-words: the tarball's sha256 is ${actual}, not ${SCOWL_SHA256}; nothing derived`);
    return 1;
  }
  const dir = mkdtempSync(join(tmpdir(), "nen-ordinary-words-"));
  try {
    const members = [...Object.values(SCOWL_FILES), COPYRIGHT_IN_TARBALL];
    const untar = spawnSync("tar", ["-xzf", tarball, "-C", dir, ...members], { encoding: "utf8" });
    if (untar.status !== 0) {
      console.error(`ordinary-words: tar could not extract the lists (${untar.error?.message ?? `exit ${String(untar.status)}`})`);
      return 1;
    }
    const read = (member: string): string => readFileSync(join(dir, member), "latin1");
    const words = deriveOrdinaryWords({
      words10: read(SCOWL_FILES.words10),
      words20: read(SCOWL_FILES.words20),
      upper10: read(SCOWL_FILES.upper10),
      upper35: read(SCOWL_FILES.upper35),
    });
    const json = renderOrdinaryWordsDoc(words);
    const copyright = readFileSync(join(dir, COPYRIGHT_IN_TARBALL));
    if (write) {
      writeFileSync(join(repo, JSON_PATH), json);
      writeFileSync(join(repo, COPYRIGHT_PATH), copyright);
      console.log(`ordinary-words: wrote ${JSON_PATH} (${words.length} words, sha256 ${wordsSha256(words)}) and ${COPYRIGHT_PATH}`);
      return 0;
    }
    const drift: string[] = [];
    if (readFileSync(join(repo, JSON_PATH), "utf8") !== json) drift.push(JSON_PATH);
    if (!readFileSync(join(repo, COPYRIGHT_PATH)).equals(copyright)) drift.push(COPYRIGHT_PATH);
    if (drift.length > 0) {
      console.error(`ordinary-words: drifted from the derivation: ${drift.join(", ")} (rerun with --write and review the diff)`);
      return 1;
    }
    console.log(`ordinary-words: ${JSON_PATH} and ${COPYRIGHT_PATH} are the derivation's (${words.length} words)`);
    return 0;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  process.exitCode = ordinaryWordsMain(process.argv.slice(2));
}
