/** A refusal this module raises; the command layer turns it into exit 2. */
export class SurfaceMirrorError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SurfaceMirrorError";
  }
}

export const MARKER_PREFIX = "<!-- GENERATED by nen surface mirror (surface: ";
const TEXT_PREFIX = "GENERATED by nen surface mirror (surface: ";
const TEXT_SUFFIX = ") -- do not edit; edit the source and regenerate";

/**
 * The marker's text, without any comment syntax: `GENERATED by nen surface
 * mirror (surface: codex[, stamp: 0.43.0]) -- do not edit; ...`.
 *
 * ASCII ONLY, and `--` rather than an em dash: this line is written into
 * somebody else's repository, read back by this same verb on a Windows checkout,
 * and compared byte for byte. A character whose encoding can vary is a drift
 * class nobody asked for.
 */
export function markerText(surface: string, stamp: string | null = null): string {
  return `${TEXT_PREFIX}${surface}${stamp === null ? "" : `, stamp: ${stamp}`}${TEXT_SUFFIX}`;
}

/** The marker as a markdown line. */
export function markerFor(surface: string, stamp: string | null = null): string {
  return `<!-- ${markerText(surface, stamp)} -->`;
}

export function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

const TEXT_RE = new RegExp(
  `^${escapeRegExp(TEXT_PREFIX)}(?<surface>[^,)]*)(?:, stamp: (?<stamp>[^)]*))?${escapeRegExp(TEXT_SUFFIX)}$`,
);
const STAMP_RE = new RegExp(`(${escapeRegExp(TEXT_PREFIX)}[^,)]*), stamp: [^)]*\\)`, "g");

export interface Marker {
  readonly surface: string;
  /** The version the mirror was generated from, or null for the unstamped form. */
  readonly stamp: string | null;
}

function parseMarkerText(text: string): Marker | null {
  const groups = TEXT_RE.exec(text.replace(/\r$/, ""))?.groups;
  if (groups === undefined) return null;
  return { surface: groups["surface"] ?? "", stamp: groups["stamp"] ?? null };
}

/**
 * The marker a committed file carries, or null when it carries none (a
 * hand-written file, or one whose banner was deleted). Markdown: the first
 * markdown line as an HTML comment. TOML: a `# ` first line. JSON: the
 * top-level `$generated` key.
 */
export function readMarker(text: string): Marker | null {
  const first = splitDocument(text).body.split("\n")[0] ?? "";
  const comment = /^<!-- (.*) -->\r?$/.exec(first);
  if (comment?.[1] !== undefined) return parseMarkerText(comment[1]);
  if (first.startsWith("# ")) return parseMarkerText(first.slice(2));
  // A script: the shebang owns line 1, so the marker is the `# ` line under it.
  if (first.startsWith("#!")) {
    const second = text.split("\n")[1] ?? "";
    if (second.startsWith("# ")) return parseMarkerText(second.slice(2));
  }
  if (text.trimStart().startsWith("{")) {
    try {
      const parsed = JSON.parse(text) as unknown;
      if (typeof parsed === "object" && parsed !== null && !Array.isArray(parsed)) {
        const value = (parsed as Record<string, unknown>)["$generated"];
        if (typeof value === "string") return parseMarkerText(value);
      }
    } catch {
      return null;
    }
  }
  return null;
}

/** `text` with every marker's `, stamp: <v>` removed, so two generations differing only in stamp compare equal. */
export function withoutStamp(text: string): string {
  return text.replace(STAMP_RE, "$1)");
}

