/**
 * The files under `outDir` this verb considers ITS OWN -- the only ones it will
 * ever delete, and the only ones a check calls EXTRA.
 *
 * TWO CONDITIONS, AND THE SECOND IS THE MARKER (zheref/nen#149, review). A file
 * is ours only if it sits at one of the row's own locations AND carries a
 * generated marker. The first cut had only the location test, which made
 * `writeSurfaceMirror` inconsistent with itself: it REFUSED to overwrite an
 * unmarked `<name>/SKILL.md` and then happily DELETED one whose source had gone
 * -- the same file, the same hand, destroyed instead of protected because it
 * was orphaned rather than shadowed. "This verb never touches a file it did not
 * write" has to hold for the delete path too, or it is not a property.
 *
 * The gate is deliberately "carries A marker", not "carries THIS surface's": a
 * file generated for another surface and now sourceless is still this
 * generator's output, and is the case `check` reports as EXTRA and `generate`
 * removes. And `check` and `generate` read the SAME list, so what one calls
 * extra is exactly what the other deletes -- an `extra` a regenerate could not
 * clear would be drift nobody can fix.
 *
 * The row's OTHER locations are in the universe on the same terms: its hook
 * manifest, its rules directory's files, its permission pack, its model
 * fragment, its persona TOML files. A VERBATIM row writes no marker, so for it
 * the location test is the whole test: a plugin's own tree has no hand-written
 * files to tell apart from generated ones, because none of them is generated.
 *
 * Anything else a repository keeps in the mirror directory (a README, a
 * reference file beside a SKILL.md, an unrelated subdirectory, a SKILL.md
 * somebody wrote by hand) is outside the universe and is never touched, which
 * is ../canon/mirror.ts's rule and the reason its own docstring gives for
 * having one.
 */
export function universeFiles(outDir: string, row: SurfaceRow): readonly string[] {
  const ours = (relative: string): boolean => {
    const path = join(outDir, ...relative.split("/"));
    if (!existsSync(path) || !statSync(path).isFile()) return false;
    return row.verbatim || readMarker(readFileSync(path, "utf8")) !== null;
  };
  const isDir = (path: string): boolean => existsSync(path) && statSync(path).isDirectory();
  // A `_`-prefixed file is a shared include on the source side (zheref/nen
  // #223) and is CARRIED as one (S11), so it is inside the universe on every
  // row like any persona file: generated, checked, and deleted as an orphan
  // when its source goes.
  const filesIn = (dir: string, extension: string): readonly string[] => {
    const absolute = join(outDir, ...dir.split("/"));
    if (!isDir(absolute)) return [];
    return readdirSync(absolute)
      .sort()
      .filter((entry): boolean => entry.endsWith(extension))
      .map((entry): string => `${dir}/${entry}`);
  };

  if (!existsSync(outDir)) return [];
  const found: string[] = [];
  const skillsRoot = row.skillsDir === "" ? outDir : join(outDir, ...row.skillsDir.split("/"));
  if (isDir(skillsRoot)) {
    for (const entry of readdirSync(skillsRoot).sort()) {
      if (!isDir(join(skillsRoot, entry))) continue;
      const relative = skillPath(row, entry);
      if (ours(relative)) found.push(relative);
    }
  }
  const candidates: string[] = [];
  const rule = row.agents;
  if (rule.kind === "files") candidates.push(...filesIn(rule.dir, rule.extension));
  else candidates.push(rule.file);
  if (row.agentToml !== null) candidates.push(...filesIn(row.agentToml.dir, ".toml"));
  if (row.hooks !== null) {
    candidates.push(row.hooks.file);
    if (row.hooks.scriptsDir !== null) candidates.push(...filesIn(row.hooks.scriptsDir, ""));
  }
  if (row.pluginManifest !== null) candidates.push(row.pluginManifest.file);
  if (row.rules !== null) candidates.push(...filesIn(row.rules.dir, row.rules.extension));
  if (row.permissions !== null) candidates.push(row.permissions.file);
  if (row.subagentModelFragment !== null) candidates.push(row.subagentModelFragment.file);
  for (const candidate of candidates) if (ours(candidate)) found.push(candidate);
  return [...new Set(found)].sort();
}

