/**
 * `<prefix><name>` rewritten to the surface's own spelling, everywhere it
 * appears -- INCLUDING names that are not in the mirrored set, because a skill
 * that points at a sibling points at it by the same prefix and a half-rewritten
 * document is worse than an unrewritten one.
 *
 * A `{name}` the surface has no spelling for is left exactly as written: this
 * verb never invents an invocation syntax for a surface whose documentation
 * states none.
 */
export function rewriteInvocations(text: string, row: SurfaceRow, prefix: string | null): string {
  if (prefix === null || prefix === "" || row.invocation === null) return text;
  const pattern = new RegExp(`(?<![A-Za-z0-9_-])${escapeRegExp(prefix)}([A-Za-z0-9][A-Za-z0-9_-]*)`, "g");
  return text.replace(pattern, (_whole, name: string): string => invocationFor(row, name) ?? _whole);
}

/** The whole `description:` value -- its own line plus every continuation -- as one space-joined string. */
export function descriptionText(entries: readonly FrontmatterEntry[]): string {
  const entry = entries.find((candidate): boolean => candidate.key === "description");
  if (entry === undefined) return "";
  return [inlineValue(entry), ...entry.lines.slice(1).map((line): string => line.trim())]
    .filter((part): boolean => part !== "")
    .join(" ")
    .replace(/\r/g, "");
}

/**
 * The first sentence of `text`, trimmed to `budget` characters. A sentence
 * ends at the first `.`, `!` or `?` followed by whitespace or the end; a
 * sentence longer than the budget is cut at the budget's last whitespace, or
 * hard at the budget when it has none.
 */
export function firstSentence(text: string, budget: number): string {
  const match = /^(.*?[.!?])(?:\s|$)/.exec(text);
  const sentence = (match?.[1] ?? text).trim();
  if (sentence.length <= budget) return sentence;
  const cut = sentence.slice(0, budget);
  const space = cut.lastIndexOf(" ");
  return (space > 0 ? cut.slice(0, space) : cut).trim();
}

function skillFile(options: GenerateOptions, skill: SourceSkill, truncated: string[]): GeneratedFile {
  const row = options.row;
  const document = splitDocument(skill.text);
  if (!document.hasFrontmatter) {
    throw new SurfaceMirrorError(
      `'${skill.relative}' has no '---' frontmatter block. Every surface in the table identifies a skill by its frontmatter, so a file without one cannot be adapted -- only copied, which is not what this verb promises.`,
    );
  }
  for (const key of row.skillRequired) {
    if (!hasValue(document.entries, key)) {
      throw new SurfaceMirrorError(
        `'${skill.relative}' has no '${key}' in its frontmatter, and '${row.surface}' documents it as required (${row.source}). Add it to the source rather than to the mirror.`,
      );
    }
  }
  const path = skillPath(row, skill.name);
  if (row.verbatim) return { path, content: skill.text };

  let entries: readonly FrontmatterEntry[] = document.entries;
  if (row.descriptionBudget !== null) {
    const description = descriptionText(entries);
    if (description.length > row.descriptionBudget && !entries.some((entry): boolean => entry.key === "summary")) {
      const summary: FrontmatterEntry = {
        key: "summary",
        lines: [`summary: ${firstSentence(description, row.descriptionBudget)}`],
      };
      const at = entries.findIndex((entry): boolean => entry.key === "description");
      entries = [...entries.slice(0, at + 1), summary, ...entries.slice(at + 1)];
      truncated.push(skill.name);
    }
  }
  const front = renderFrontmatter(entries, new Set(row.skillKeys));
  const content = `${front}${markerFor(row.surface, options.stamp ?? null)}\n${document.body}`;
  return { path, content: rewriteInvocations(content, row, options.invocationPrefix) };
}

interface AgentOutput {
  readonly files: readonly GeneratedFile[];
  readonly droppedInherit: readonly string[];
  readonly undocumentedAliases: readonly string[];
  readonly modelMapped: readonly string[];
  readonly notes: readonly string[];
}

function agentFiles(options: GenerateOptions): AgentOutput {
  const row = options.row;
  const rule = row.agents;
  const stamp = options.stamp ?? null;
  const models = options.models ?? null;
  const droppedInherit: string[] = [];
  const undocumentedAliases: string[] = [];
  const modelMapped: string[] = [];
  const notes: string[] = [];
  const includes = options.includes ?? [];
  if (options.agents.length === 0 && includes.length === 0) return { files: [], droppedInherit, undocumentedAliases, modelMapped, notes };

  /** `model:` through --models, for a persona whose entries the surface reads as frontmatter. */
  const mapped = (agent: SourceAgent, entries: readonly FrontmatterEntry[]): readonly FrontmatterEntry[] => {
    if (models === null || !row.agentModelMap) return entries;
    const result = rewriteModel(row, models, entries, agent.relative);
    if (result.droppedInherit) droppedInherit.push(agent.stem);
    if (result.undocumentedAlias !== null) undocumentedAliases.push(`${agent.stem}: ${result.undocumentedAlias}`);
    if (result.mappedToInherit !== null) modelMapped.push(`${agent.stem}: ${result.mappedToInherit} -> inherit`);
    return result.entries;
  };

  if (rule.kind === "files") {
    const files = options.agents.map((agent): GeneratedFile => {
      const path = `${rule.dir}/${agent.stem}${rule.extension}`;
      if (row.verbatim) return { path, content: agent.text };
      const document = splitDocument(agent.text);
      for (const key of rule.required) {
        if (!hasValue(document.entries, key)) {
          throw new SurfaceMirrorError(
            `'${agent.relative}' has no '${key}' in its frontmatter, and '${row.surface}' documents it as required for a persona (${row.agentSource}). Add it to the source rather than to the mirror.`,
          );
        }
      }
      const front = renderFrontmatter(mapped(agent, document.entries), new Set(rule.keys));
      // A `files` surface reads a persona AS frontmatter-bearing markdown, so a
      // mirror with an EMPTY block cannot be one (zheref/nen#149, review).
      // Emitting it anyway would write a persona file with no frontmatter at
      // all -- nothing for the surface to route on, and the marker sitting on
      // line 1 of a document whose shape that surface's own page describes
      // differently. That the row REQUIRES no key is a statement about which
      // keys must be filled in; it is not a statement that the block itself is
      // optional. Both ways of arriving at an empty block are refused -- no
      // fence in the source, or a fence holding only keys this surface does not
      // read -- because the file that would be written is the same file.
      if (front === "") {
        const because = document.hasFrontmatter
          ? `its frontmatter holds none of the keys this surface reads (${rule.keys.join(", ")})`
          : "it has no '---' frontmatter block at all";
        throw new SurfaceMirrorError(
          `'${agent.relative}' would mirror to a persona file with no frontmatter, because ${because}. '${row.surface}' reads a persona as frontmatter-bearing markdown (${row.agentSource}), so there would be nothing for it to route on. Fix the source rather than the mirror.`,
        );
      }
      const content = `${front}${markerFor(row.surface, stamp)}\n${document.body}`;
      return { path, content: rewriteInvocations(content, row, options.invocationPrefix) };
    });
    // The includes, beside the personas (S11): frontmatter reduced the same
    // way, marker after it, body verbatim -- and NO required-key check, no
    // empty-frontmatter refusal and no model rewriting, because an include
    // is not a persona: nothing routes on it, and a persona reads it by path.
    for (const include of includes) {
      const path = `${rule.dir}/${include.stem}${rule.extension}`;
      if (row.verbatim) {
        files.push({ path, content: include.text });
        continue;
      }
      const document = splitDocument(include.text);
      const front = renderFrontmatter(document.entries, new Set(rule.keys));
      const content = `${front}${markerFor(row.surface, stamp)}\n${document.body}`;
      files.push({ path, content: rewriteInvocations(content, row, options.invocationPrefix) });
    }
    return { files, droppedInherit, undocumentedAliases, modelMapped, notes };
  }

  // The appendix: ONE document, a heading per persona, the persona's prose
  // underneath. Its frontmatter is dropped whole rather than filtered -- the
  // file this lands in has no frontmatter concept at all, and a stray `---`
  // fence in the middle of a prose document renders as a horizontal rule.
  const hashes = "#".repeat(rule.headingLevel);
  const section = (agent: SourceAgent, heading: string): string => {
    const body = splitDocument(agent.text).body.replace(/^\n+/, "").replace(/\s+$/, "");
    return `${hashes} ${heading}\n\n${body}\n`;
  };
  // The includes follow the personas as `## _<stem>` sections (S11): a
  // persona's "read _review-preamble first" then lands on a heading in the
  // same document rather than on a file the surface never received.
  const sections = [
    ...options.agents.map((agent): string => section(agent, agent.name)),
    ...includes.map((include): string => section(include, include.stem)),
  ];
  const appendix = rewriteInvocations(
    `${markerFor(row.surface, stamp)}\n\n${sections.join("\n")}`,
    row,
    options.invocationPrefix,
  );
  const files: GeneratedFile[] = [{ path: rule.file, content: appendix }];
  if (rule.warnBytes !== null) {
    const bytes = Buffer.byteLength(appendix, "utf8");
    if (bytes > rule.warnBytes) {
      notes.push(
        `${rule.file} is ${bytes} bytes, past the ${rule.warnBytes}-byte read limit the surface documents (${row.agentSource}); a persona past the cut-off is one the surface never meets`,
      );
    }
  }

  // The machine-readable persona files beside the appendix, only when a
  // model map was given: `model` is the one field the prose cannot carry,
  // and it is the reason the files exist.
  if (row.agentToml !== null && models !== null) {
    for (const agent of options.agents) {
      const document = splitDocument(agent.text);
      const result = rewriteModel(row, models, document.entries, agent.relative);
      if (result.droppedInherit) droppedInherit.push(agent.stem);
      if (result.undocumentedAlias !== null) undocumentedAliases.push(`${agent.stem}: ${result.undocumentedAlias}`);
      const description = descriptionText(document.entries);
      if (description === "") {
        throw new SurfaceMirrorError(
          `'${agent.relative}' has no 'description' in its frontmatter, and '${row.surface}' documents it as required for ${row.agentToml.documentedPath} (${row.agentToml.source}). Add it to the source rather than to the mirror.`,
        );
      }
      const body = rewriteInvocations(document.body.replace(/^\n+/, "").replace(/\s+$/, ""), row, options.invocationPrefix);
      const lines = [
        `# ${markerText(row.surface, stamp)}`,
        `name = ${tomlString(agent.name)}`,
        `description = ${tomlString(rewriteInvocations(description, row, options.invocationPrefix))}`,
        ...(result.alias === null || result.alias === "inherit" ? [] : [`model = ${tomlString(result.alias)}`]),
        `developer_instructions = ${tomlMultiline(body)}`,
        "",
      ];
      files.push({ path: `${row.agentToml.dir}/${agent.stem}.toml`, content: lines.join("\n") });
    }
  }
  return { files, droppedInherit, undocumentedAliases, modelMapped, notes };
}

/** Every file this run would write, sorted by path, with what the report needs to say about them. */
export function generateSurfaceMirrorReport(options: GenerateOptions): GenerateReport {
  const row = options.row;
  const stamp = options.stamp ?? null;
  const truncated: string[] = [];
  const notes: string[] = [];
  const files: GeneratedFile[] = options.skills.map((skill): GeneratedFile => skillFile(options, skill, truncated));
  const agents = agentFiles(options);
  files.push(...agents.files);
  notes.push(...agents.notes);

  let hooks: GenerateReport["hooks"] = "none";
  if (options.hooks !== undefined && options.hooks !== null) {
    if (row.hooks === null) hooks = "not supported";
    else {
      hooks = "written";
      const marker = markerText(row.surface, stamp);
      files.push({ path: row.hooks.file, content: renderHooks(row.hooks, options.hooks, marker, options.hooksRoot ?? null) });
      // The scripts travel with the manifest: a mirror installed as a plugin
      // root has to resolve `<root>/hooks/<file>` to a file it ships.
      if (row.hooks.scriptsDir !== null) {
        for (const script of readHookScripts(options.hooks)) {
          const rendered = renderHookScript(script, marker);
          const path = `${row.hooks.scriptsDir}/${script.name}`;
          files.push({ path, content: rendered.content, mode: 0o755, ...(rendered.markerless ? { markerless: true } : {}) });
          if (rendered.markerless) {
            notes.push(`${path} carries no marker: its interpreter does not read # comments, and the manifest beside it carries the marker`);
          }
        }
      }
      if (options.hooks.unmapped.length > 0) {
        notes.push(
          `--hooks carries ${options.hooks.unmapped.join(", ")}, which no row maps; only Stop, PreToolUse and SessionStart are carried`,
        );
      }
    }
  }

  let rules: GenerateReport["rules"] = "none";
  if (options.rules !== undefined && options.rules !== null) {
    if (row.rules === null) rules = "not supported";
    else {
      const rendered = renderRules(row.rules, options.rules, markerText(row.surface, stamp));
      files.push({ path: rendered.path, content: rendered.content });
      rules = { path: rendered.path, chars: rendered.chars, limit: row.rules.limit };
      if (row.rules.lineGuidance !== null && rendered.lines > row.rules.lineGuidance) {
        notes.push(
          `${rendered.path} is ${rendered.lines} lines; the surface advises under ${row.rules.lineGuidance} (${row.rules.source})`,
        );
      }
    }
  }

  let permissions: GenerateReport["permissions"] = "none";
  let permissionSurfaceRows = 0;
  let writableRootsPlaceholder = false;
  let permissionSandbox: GenerateReport["permissionSandbox"] = null;
  if (options.permissions !== undefined && options.permissions !== null) {
    if (row.permissions === null) permissions = "not supported";
    else {
      permissions = "written";
      const rendered = renderPermissions(row.permissions, options.permissions, markerText(row.surface, stamp), row.surface);
      files.push({ path: row.permissions.file, content: rendered.content });
      permissionSurfaceRows = rendered.surfaceRows;
      writableRootsPlaceholder = rendered.writableRootsPlaceholder;
      permissionSandbox = rendered.sandbox;
      if (writableRootsPlaceholder) {
        notes.push(`${row.permissions.file} carries writable_roots = [] for the installer to fill (writableRootsPlaceholder)`);
      }
    }
  }

  let manifest: GenerateReport["manifest"] = "none";
  if (options.manifest !== undefined && options.manifest !== null) {
    if (row.pluginManifest === null) manifest = "not supported";
    else {
      manifest = "written";
      files.push({
        path: row.pluginManifest.file,
        content: renderPluginManifest(row.pluginManifest, options.manifest, markerText(row.surface, stamp)),
      });
    }
  }

  if (options.models !== undefined && options.models !== null && row.subagentModelFragment !== null) {
    const fragment = row.subagentModelFragment;
    const alias = options.models.target[fragment.tier];
    if (alias === undefined) {
      throw new SurfaceMirrorError(
        `--models declares no 'models.${row.surface}.${fragment.tier}', which ${fragment.file} names as the default subagent model (${fragment.source}). Add the tier or omit --models.`,
      );
    }
    files.push({
      path: fragment.file,
      content: `# ${markerText(row.surface, stamp)}\n# Merge into ${fragment.documentedPath}; this fragment is never the live file.\n[agents]\ndefault_subagent_model = ${tomlString(alias)}\n`,
    });
  }

  return {
    files: files.sort((left, right): number => (left.path < right.path ? -1 : left.path > right.path ? 1 : 0)),
    truncated: truncated.sort(),
    droppedInherit: [...new Set(agents.droppedInherit)].sort(),
    undocumentedAliases: [...new Set(agents.undocumentedAliases)].sort(),
    modelMapped: [...new Set(agents.modelMapped)].sort(),
    hooks,
    rules,
    permissions,
    permissionSurfaceRows,
    writableRootsPlaceholder,
    permissionSandbox,
    manifest,
    notes,
    includes: (options.includes ?? []).map((include): string => include.relative),
  };
}

/** Every file this run would write, sorted by path. */
export function generateSurfaceMirror(options: GenerateOptions): readonly GeneratedFile[] {
  return generateSurfaceMirrorReport(options).files;
}

