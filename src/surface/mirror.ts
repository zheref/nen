export interface MirrorReport {
  readonly surface: string;
  readonly ok: readonly string[];
  readonly missing: readonly string[];
  readonly extra: readonly string[];
  readonly stale: readonly string[];
  readonly handEdited: readonly string[];
}

/**
 * The committed mirror against a fresh generation. With `stamp`, a file whose
 * marker carries no stamp or a different one is STALE (older is the case that
 * matters; newer is not this source's either); without it, stamps are masked
 * on both sides and never a drift class.
 */
export function checkSurfaceMirror(
  outDir: string,
  generated: readonly GeneratedFile[],
  row: SurfaceRow,
  stamp: string | null = null,
): MirrorReport {
  const ok: string[] = [];
  const missing: string[] = [];
  const stale: string[] = [];
  const handEdited: string[] = [];

  for (const file of generated) {
    const path = join(outDir, ...file.path.split("/"));
    if (!existsSync(path) || !statSync(path).isFile()) {
      missing.push(file.path);
      continue;
    }
    const existing = readFileSync(path, "utf8");
    if (row.verbatim || file.markerless === true) {
      (existing === file.content ? ok : handEdited).push(file.path);
      continue;
    }
    const marker = readMarker(existing);
    if (marker === null) handEdited.push(file.path);
    else if (marker.surface !== row.surface) stale.push(file.path);
    // A stamp that is not a version is STALE, not an error (N14): the file was
    // generated by something whose stamp this build cannot read, which is the
    // same fact as "not this source's" -- and a check that exited 2 over it
    // could never report the file it was asked about.
    else if (stamp !== null && (marker.stamp === null || !isVersion(marker.stamp) || compareVersions(marker.stamp, stamp) !== 0)) stale.push(file.path);
    else if (withoutStamp(existing) !== withoutStamp(file.content)) handEdited.push(file.path);
    // The same bytes under a different mode is a hand edit too (N6): a hook
    // script at 0644 is one the surface cannot run.
    else if (file.mode !== undefined && modeOf(path) !== file.mode) handEdited.push(file.path);
    else ok.push(file.path);
  }

  const keep = new Set(generated.map((file): string => file.path));
  const extra = universeFiles(outDir, row).filter((path): boolean => !keep.has(path));

  return {
    surface: row.surface,
    ok: ok.sort(),
    missing: missing.sort(),
    extra: extra.sort(),
    stale: stale.sort(),
    handEdited: handEdited.sort(),
  };
}

export function mirrorReportOk(report: MirrorReport): boolean {
  return (
    report.missing.length === 0 &&
    report.extra.length === 0 &&
    report.stale.length === 0 &&
    report.handEdited.length === 0
  );
}
